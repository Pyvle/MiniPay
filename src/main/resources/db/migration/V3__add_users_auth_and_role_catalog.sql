CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    rank INTEGER NOT NULL,

    CONSTRAINT check_rank
        CHECK (rank > 0),
    CONSTRAINT check_name
        CHECK (btrim(name) <> ''),
        CHECK (upper(btrim(name)) NOT IN ('USER', 'SUPER_ADMIN'))
);

CREATE UNIQUE INDEX roles_name_unique
        ON roles (lower(btrim(name)));

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,

    CONSTRAINT check_code
        CHECK (btrim(code) <> ''),
        CHECK (code = upper(btrim(code)))
);

CREATE UNIQUE INDEX permissions_code_unique
        ON permissions (lower(btrim(code)));

ALTER TABLE users 
    ADD COLUMN password_hash VARCHAR(255) NOT NULL,
    ADD COLUMN system_role VARCHAR(50) NOT NULL,
    ADD COLUMN state VARCHAR(50) NOT NULL,
    ADD COLUMN main_role_id BIGINT,
    
    ADD CONSTRAINT fk_users_main_role
        FOREIGN KEY (main_role_id)
        REFERENCES roles(id),

    ADD CONSTRAINT check_system_role
        CHECK (system_role IN ('USER', 'SUPER_ADMIN')),
    ADD CONSTRAINT check_state
        CHECK (state IN ('ACTIVE', 'BLOCKED')),
    ADD CONSTRAINT check_super_admin
        CHECK (system_role <> 'SUPER_ADMIN' OR main_role_id IS NULL);